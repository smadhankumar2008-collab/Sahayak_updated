def generate_answer(query: str, evidence: List[Dict], language: str = "en", query_type: str = "GENERAL_COOPERATIVE", history: List[Dict] = None) -> Dict:
    """
    CRITICAL LANGUAGE LOCK - Main entry point
    SELECTED LANGUAGE = RESPONSE LANGUAGE - Single Source of Truth
    """
    # DEBUG LOGGING - As per requirement
    lang_config = get_language_config(language)
    print(f"\n{'='*60}")
    print(f"[LANGUAGE LOCK DEBUG] Selected Language: {language}")
    print(f"[LANGUAGE LOCK DEBUG] Language Name: {lang_config.get('name')} / {lang_config.get('nativeName')}")
    print(f"[LANGUAGE LOCK DEBUG] Question: {query[:100]}")
    print(f"[LANGUAGE LOCK DEBUG] Query Type: {query_type}")
    print(f"[LANGUAGE LOCK DEBUG] Evidence count: {len(evidence) if evidence else 0}")
    print(f"[LANGUAGE LOCK DEBUG] TTS Language: {lang_config.get('ttsLanguage')}")
    print(f"{'='*60}\n")
    
    logger.info(f"Selected Language: {language}, Name: {lang_config.get('nativeName')}, Question: {query[:50]}, Type: {query_type}")
    
    # Validate selected language - NEVER fallback to English if user selected non-English
    if language not in LANGUAGE_CONFIG:
        print(f"[LANGUAGE LOCK] WARNING: Invalid language {language}, defaulting to en")
        language = "en"
    
    if not evidence or len(evidence) == 0:
        print(f"[LANGUAGE LOCK] No evidence, returning fallback in {language}")
        return {
            "answer": get_fallback_message(language), 
            "sources": [], 
            "evidence_level": "none", 
            "grounded": False, 
            "query_type": query_type, 
            "language": language,
            "selected_language": language,
            "tts_language": lang_config.get("ttsLanguage", f"{language}-IN")
        }
    
    avg_score = sum(doc.get("retrieval_score", 0) for doc in evidence) / len(evidence) if evidence else 0
    evidence_level = get_evidence_level(avg_score, len(evidence))
    
    if evidence_level == "none":
        print(f"[LANGUAGE LOCK] Evidence level none, returning fallback in {language}")
        return {
            "answer": get_fallback_message(language), 
            "sources": [], 
            "evidence_level": evidence_level, 
            "grounded": False, 
            "query_type": query_type, 
            "language": language,
            "selected_language": language,
            "tts_language": lang_config.get("ttsLanguage", f"{language}-IN")
        }
    
    # Try LLM with strict language lock
    llm_result = generate_with_llm_strict(query, evidence, language, query_type, history)
    if llm_result and llm_result[0]:
        llm_answer, sources = llm_result
        if llm_answer:
            # Validate again
            is_valid, detected_lang, conf = is_response_in_selected_language(llm_answer, language)
            print(f"[LANGUAGE LOCK] LLM result validation - Selected: {language}, Detected: {detected_lang}, Valid: {is_valid}")
            if is_valid or language == "en":
                print(f"[LANGUAGE LOCK] Returning LLM answer in {language}")
                return {
                    "answer": llm_answer, 
                    "sources": sources, 
                    "evidence_level": evidence_level, 
                    "grounded": True, 
                    "query_type": query_type, 
                    "language": language,
                    "selected_language": language,
                    "tts_language": lang_config.get("ttsLanguage", f"{language}-IN"),
                    "generation_method": "llm",
                    "detected_response_language": detected_lang,
                    "language_valid": is_valid
                }
            else:
                print(f"[LANGUAGE LOCK] LLM answer failed validation, falling back to extractive")
    
    # Fallback to extractive with strict language lock
    extractive_answer, extractive_sources = generate_smart_extractive_strict(query, evidence, language, query_type)
    
    # Final validation
    is_valid, detected_lang, conf = is_response_in_selected_language(extractive_answer, language)
    print(f"[LANGUAGE LOCK] Final validation - Selected: {language}, Detected: {detected_lang}, Valid: {is_valid}, Conf: {conf:.2f}")
    print(f"[LANGUAGE LOCK DEBUG] LLM Response Language: {detected_lang}, TTS Language: {lang_config.get('ttsLanguage')}")
    
    if not is_valid and language != "en":
        # Maximum retry failed - return error in selected language
        print(f"[LANGUAGE LOCK] FINAL FAILED - Returning error message in {language}")
        return {
            "answer": get_fallback_error_message(language), 
            "sources": extractive_sources, 
            "evidence_level": evidence_level, 
            "grounded": False, 
            "query_type": query_type, 
            "language": language,
            "selected_language": language,
            "tts_language": lang_config.get("ttsLanguage", f"{language}-IN"),
            "generation_method": "error_fallback",
            "detected_response_language": detected_lang,
            "language_valid": False
        }
    
    return {
        "answer": extractive_answer, 
        "sources": extractive_sources, 
        "evidence_level": evidence_level, 
        "grounded": True if evidence_level in ["high", "medium"] else False, 
        "query_type": query_type, 
        "language": language,
        "selected_language": language,
        "tts_language": lang_config.get("ttsLanguage", f"{language}-IN"),
        "generation_method": "extractive",
        "detected_response_language": detected_lang,
        "language_valid": is_valid
    }
